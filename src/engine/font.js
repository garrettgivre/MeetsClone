export const FINE_ROWS = 10; // fine pixels in a glyph's height (5 normal pixels)
/** Every glyph of the fine font, for tests: { char: rows }. */
export const FINE_GLYPHS = FINE;
export const SMALL_GLYPHS = SMALL;

const GLYPHS = {};
for (const ch in FINE) GLYPHS[ch] = { w: FINE[ch][0].length / 2, rows: FINE[ch] }; // w in normal pixels
const FALLBACK = GLYPHS['?'];
export const LINE_H = 7;

function glyph(ch) {
  return GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || FALLBACK;
}

/** A character's small 3x5 pixel rows ('#' = ink), for lettering painted into art (shop signs). */
export function glyphRows(ch) { return SMALL[ch] || SMALL[ch.toUpperCase()] || SMALL['?']; }

export function measure(str) {
  let w = 0;
  for (const ch of str) w += glyph(ch).w + 1;
  return Math.max(0, w - 1);
}

/** Draw text at (x, y) in normal pixels. opts: { align: 'left'|'center'|'right', shadow: colour } */
export function text(scr, str, x, y, color, opts = {}) {
  str = String(str);
  if (opts.align === 'center') x -= Math.floor(measure(str) / 2);
  else if (opts.align === 'right') x -= measure(str);
  if (opts.shadow !== undefined) text(scr, str, x + 1, y + 1, opts.shadow);
  let cx = x;
  const Y = Math.floor(y) * 2;
  for (const ch of str) {
    const g = glyph(ch);
    const X = Math.floor(cx) * 2;
    for (let j = 0; j < FINE_ROWS; j++) {
      const row = g.rows[j];
      for (let i = 0; i < row.length; i++) if (row[i] === '#') scr.hpset(X + i, Y + j, color);
    }
    cx += g.w + 1;
  }
  return cx - x - 1;
}

/** Split text into lines that fit `width` pixels. '\n' forces a break. */
export function wrap(str, width) {
  const lines = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? line + ' ' + word : word;
      if (measure(next) > width && line) { lines.push(line); line = word; }
      else line = next;
    }
    lines.push(line);
  }
  return lines;
}
