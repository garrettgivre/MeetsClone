// Clothes, typed by hand at the fine pixel size (one character to a fine
// pixel, a one-pixel ink outline). The same drawing is put on the pet
// (src/game/pet-art.js) and shown as the item's icon in the shop and wardrobe.
// Letters are the sprite key of src/engine/sprite.js: `5 6 7 8` take the
// item's own colour (CLOTHES[id].color), darkest to lightest; the rest are
// fixed colours (o ink, w white, m mist, K shade, Y y u gold, and so on).
// Every grid has an even width and height.
//
//   HATS  sit on top of the head: the pivot's row is the one that rests on the
//         head (rows under it overlap the head), in the column of the head's
//         crown; `offset` moves a hat sideways along the head.
//   FACE  glasses (a ring round each eye, in three sizes: the renderer takes
//         the smallest that clears the eye and adds the bridge) and things
//         stuck on the brow over one eye.
//   NECK  hang under the chin: the pivot is the middle of the top row.
//
// Not drawn yet: clothes that cover a body (sweater, overalls, dress, sailor
// top, apron), the scarf and sash, the cape and shoes. Those need a drawing
// for each body plan.
