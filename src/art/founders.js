// Hand-pixelled founder sprites. Each founder is a complete character drawn
// by hand (see docs/STYLE.md), with a small curated palette and anchor points
// so the game can animate it (breathing, blinking, expressions).
//
// Grid conventions:
//   o  dark outline (shadow side)      O  lit outline (a dark shade of the body colour)
//   1  shadow   2  base   3  light   4  shine
//   k  ink (eyes, nose, mouth)   K  soft ink (lower eye)   w  white glint
//   Other letters are per-founder, defined in `key`.

import { sprite } from '../engine/sprite.js';

export const FOUNDER_ART = {};

function founder(name, def) {
  def.spr = sprite(def.rows, def.key);
  FOUNDER_ART[name] = def;
}

