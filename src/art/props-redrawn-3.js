// Pieces redrawn as actual things rather than tidy shapes (the owner: "Don't
// rely on perfect ovals and circles and squares and shapes. Make actual
// items."). Each starts from what the object is and what it is made of, with
// an outline typed row by row, not worked out from a circle. Loaded after the
// sets' own files, so these replace theirs.
//
// Rows here are typed from the left and left ragged on the right: defineProp
// fills a short row out with empty cells, so only the left edge needs counting.
// Leaves and wood are typed in letters and renamed to the usual digits:
//   o leaf outline (1)   S leaf shade (2)   M leaf (3)   L leaf light (4)
//   p wood dark (5)      Q wood shade (6)   q wood (7)   P wood light (8)
// Everything else is the usual roles of props.js.
import { defineProp } from './props.js';

