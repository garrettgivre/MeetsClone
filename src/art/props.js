// Hand-pixelled town props: trees, bushes, rocks, flowers, clouds and more.
//
// Each prop is a text grid at the town's full pixel density (one character =
// one hi-res pixel), finished by hand. Characters are colour roles so one
// drawing can be recoloured:
//   1-4  leaf ramp (1 darkest .. 4 lightest)     5-8  wood ramp
//   a-d  accent ramp (flowers, cloud undersides)  e-h  stone ramp
//   A-D  wall ramp    r s t u  roof ramp    x y z Z  glass ramp
//   w white   k ink   m mist   v silver   n grey   . empty
// Light comes from the upper left. `at` is the anchor: the point that sits on
// the ground (usually the bottom centre).
//
// Draw one with stampProp(set, name, x, y, { leaf, wood, accent, stone, flip }).

export const PROPS = {};

const ROLE = { 1: ['leaf', 0], 2: ['leaf', 1], 3: ['leaf', 2], 4: ['leaf', 3], 5: ['wood', 0], 6: ['wood', 1], 7: ['wood', 2], 8: ['wood', 3],
  a: ['accent', 0], b: ['accent', 1], c: ['accent', 2], d: ['accent', 3], e: ['stone', 0], f: ['stone', 1], g: ['stone', 2], h: ['stone', 3],
  A: ['wall', 0], B: ['wall', 1], C: ['wall', 2], D: ['wall', 3], r: ['roof', 0], s: ['roof', 1], t: ['roof', 2], u: ['roof', 3],
  x: ['glass', 0], y: ['glass', 1], z: ['glass', 2], Z: ['glass', 3] };
const FIXED = { w: 'white', k: 'ink', m: 'mist', v: 'silver', n: 'gray' };
export const DEFAULT_RAMPS = { leaf: 'green', wood: 'brown', accent: 'pink', stone: 'slate', wall: 'cream', roof: 'red', glass: 'sky' };

function prop(name, rows, { at = null, ramps = {} } = {}) {
  const w = Math.max(...rows.map(r => r.length));
  PROPS[name] = { name, rows: rows.map(r => r.padEnd(w, '.')), w, h: rows.length, at: at || [w >> 1, rows.length - 1], ramps };
}

/** Stamp a prop with its anchor at (x, y). set(x, y, colourName) draws one hi-res pixel. */
export function stampProp(set, name, x, y, { flip = false, ...ramps } = {}) {
  const p = PROPS[name];
  if (!p) throw new Error(`no prop ${name}`);
  const r = { ...DEFAULT_RAMPS, ...p.ramps, ...ramps };
  for (let j = 0; j < p.h; j++) for (let i = 0; i < p.w; i++) {
    const ch = p.rows[j][i];
    if (ch === '.') continue;
    const role = ROLE[ch];
    const colour = role ? `${r[role[0]]}.${role[1]}` : FIXED[ch];
    if (!colour) continue;
    set(x - p.at[0] + (flip ? p.w - 1 - i : i), y - p.at[1] + j, colour);
  }
}

